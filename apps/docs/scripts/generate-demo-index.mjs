import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);

export const EXAMPLES_DIR = path.join(DOCS_ROOT, 'examples');
export const OUTPUT_FILE = path.join(
  DOCS_ROOT,
  '__generated__',
  'demo-index.ts'
);

const DEMO_EXTENSION = '.tsx';
const REPO_RELATIVE_EXAMPLES_DIR = 'apps/docs/examples';

const HEADER = `// Generated by apps/docs/scripts/generate-demo-index.mjs — do not edit.
// Run \`pnpm --filter @nexus_ds/docs generate:demos\` to regenerate.

import type { ComponentType } from 'react';

export interface Demo {
  /** Path under apps/docs/examples/ without the .tsx extension. */
  id: string;
  /** Path to the demo file, relative to the repository root. */
  file: string;
  /** Lazy import of the demo module; its default export is the component. */
  load: () => Promise<{ default: ComponentType }>;
  /** The demo file's full source, imports included. */
  source: string;
}
`;

const FOOTER = `export type DemoId = keyof typeof demos;

const byId: Record<string, Demo> = demos;

export function getDemo(id: string): Demo | undefined {
  return byId[id];
}
`;

/**
 * @typedef {object} DemoFile
 * @property {string} id Path under examples/ without the .tsx extension.
 * @property {string} file Path to the demo file, relative to the repo root.
 * @property {string} source The demo file's full contents.
 */

/**
 * @param {string} dir
 * @returns {string[]}
 */
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(entryPath) : [entryPath];
  });
}

/**
 * Reads a demo file as the canonical LF form of its contents. Windows
 * checkouts carry CRLF, so returning the raw bytes would make the emitted
 * index differ by platform.
 *
 * @param {string} file
 * @returns {string}
 */
function readSource(file) {
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

/**
 * Collects every demo under `examplesDir`, ordered by id.
 *
 * @param {string} [examplesDir]
 * @returns {DemoFile[]}
 */
export function collectDemos(examplesDir = EXAMPLES_DIR) {
  return walk(examplesDir)
    .filter((file) => file.endsWith(DEMO_EXTENSION))
    .map((file) => {
      const relative = path
        .relative(examplesDir, file)
        .split(path.sep)
        .join('/');
      return {
        id: relative.slice(0, -DEMO_EXTENSION.length),
        file: `${REPO_RELATIVE_EXAMPLES_DIR}/${relative}`,
        source: readSource(file),
      };
    })
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/**
 * Renders the index module for the given demos.
 *
 * @param {DemoFile[]} demos
 * @returns {string}
 */
export function renderDemoIndex(demos) {
  const entries = demos
    .map((demo) =>
      [
        `  ${JSON.stringify(demo.id)}: {`,
        `    id: ${JSON.stringify(demo.id)},`,
        `    file: ${JSON.stringify(demo.file)},`,
        `    load: () => import(${JSON.stringify(`../examples/${demo.id}`)}),`,
        `    source: ${JSON.stringify(demo.source)},`,
        `  },`,
      ].join('\n')
    )
    .join('\n');

  const literal = entries ? `{\n${entries}\n}` : '{}';

  return `${HEADER}
export const demos = ${literal} satisfies Record<string, Demo>;

${FOOTER}`;
}

/**
 * Regenerates the demo index on disk and returns what it wrote.
 *
 * @param {{ examplesDir?: string, outputFile?: string }} [options]
 */
export function generateDemoIndex({
  examplesDir = EXAMPLES_DIR,
  outputFile = OUTPUT_FILE,
} = {}) {
  const demos = collectDemos(examplesDir);
  const output = renderDemoIndex(demos);

  mkdirSync(path.dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, output, 'utf8');

  return { demos, output };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { demos } = generateDemoIndex();
  const plural = demos.length === 1 ? 'demo' : 'demos';
  console.log(
    `demo-index: ${demos.length} ${plural} -> ${path.relative(DOCS_ROOT, OUTPUT_FILE)}`
  );
}
