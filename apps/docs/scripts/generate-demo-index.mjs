import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  watch,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DOCS_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);

export const EXAMPLES_DIR = path.join(DOCS_ROOT, 'examples');
export const GENERATED_DIR = path.join(DOCS_ROOT, '__generated__');

const DEMO_EXTENSION = '.tsx';
const INDEX_FILE = 'demo-index.ts';
const MODULES_DIR = 'demos';
const BOUNDARY_SUFFIX = '.client';
const WATCH_DEBOUNCE_MS = 50;

const GENERATED_BY =
  '// Generated by apps/docs/scripts/generate-demo-index.mjs — do not edit.';
const REGENERATE_HINT =
  '// Run `pnpm --filter @nexus_ds/docs generate:demos` to regenerate.';

const INDEX_HEADER = `${GENERATED_BY}
${REGENERATE_HINT}

import type { ComponentType } from 'react';

export interface Demo {
  /** Path under apps/docs/examples/ without the .tsx extension. */
  id: string;
  /**
   * Loads the demo's component and its own source text together. Both live in
   * a per-demo chunk, so a page pays for the demos it renders rather than for
   * every demo in the corpus.
   */
  load: () => Promise<{ Component: ComponentType; source: string }>;
}
`;

const INDEX_FOOTER = `export type DemoId = keyof typeof demos;

const byId = new Map<string, Demo>(Object.entries(demos));

export function getDemo(id: string): Demo {
  const demo = byId.get(id);

  if (!demo) {
    throw new Error(
      \`Unknown demo id: \${id}. Add apps/docs/examples/\${id}.tsx, or fix the id.\`
    );
  }

  return demo;
}
`;

/**
 * @typedef {object} DemoFile
 * @property {string} id Path under examples/ without the .tsx extension.
 * @property {string} source The demo file's full contents.
 */

/**
 * Lists every file under `dir`, recursively.
 *
 * @param {string} dir
 * @returns {string[]}
 */
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(entryPath) : [entryPath];
  });
}

/**
 * Reads a file as the canonical LF form of its contents. Windows checkouts
 * carry CRLF, so comparing or emitting the raw bytes would make the result
 * differ by platform.
 *
 * @param {string} file
 * @returns {string}
 */
function readCanonical(file) {
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

/**
 * Writes `content` only when it differs from what is on disk, so a dev-server
 * rebuild leaves untouched demos' modules — and their bundler chunks — alone.
 * The comparison ignores line endings, so a CRLF checkout counts as unchanged.
 *
 * @param {string} file
 * @param {string} content
 */
function writeIfChanged(file, content) {
  if (existsSync(file) && readCanonical(file) === content) {
    return;
  }

  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
}

/**
 * Removes every directory under `dir` — `dir` itself included — that has no
 * files left in it.
 *
 * @param {string} dir
 */
function pruneEmptyDirs(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      pruneEmptyDirs(path.join(dir, entry.name));
    }
  }

  if (readdirSync(dir).length === 0) {
    rmSync(dir, { recursive: true });
  }
}

/**
 * Deletes everything under `outputDir` that this run did not write, leaving
 * every live file — and its mtime — untouched. The scope is the whole output
 * directory, matching the `outputs` this package's turbo task declares, so a
 * stray file anywhere under it is cleared by a regeneration.
 *
 * @param {string} outputDir
 * @param {Set<string>} keep Paths of the files that should survive.
 */
function pruneOrphans(outputDir, keep) {
  for (const file of walk(outputDir)) {
    if (!keep.has(file)) {
      rmSync(file);
    }
  }

  pruneEmptyDirs(outputDir);
}

/**
 * The per-demo module's import specifier for its example, relative to the
 * module's own nesting under `__generated__/demos/`.
 *
 * @param {string} id
 * @returns {string}
 */
function exampleSpecifier(id) {
  return `${'../'.repeat(id.split('/').length + 1)}examples/${id}`;
}

/**
 * The per-demo module's import specifier for its own client boundary, which
 * sits beside it. Appending `.ts` gives the boundary's path under
 * `__generated__/demos/`, so specifier and disk path cannot drift apart.
 *
 * @param {string} id
 * @returns {string}
 */
function boundarySpecifier(id) {
  return `./${path.posix.basename(id)}${BOUNDARY_SUFFIX}`;
}

/**
 * Collects every demo under `examplesDir`, ordered by id. An id with a
 * `_`-prefixed segment is skipped, so shared helpers and private folders can
 * live beside the demos without becoming addressable demos themselves. A dot
 * in an id is rejected rather than skipped: `foo.client.tsx` would generate
 * its module at the path `foo.tsx`'s boundary already owns.
 *
 * @param {string} [examplesDir]
 * @returns {DemoFile[]}
 */
export function collectDemos(examplesDir = EXAMPLES_DIR) {
  if (!existsSync(examplesDir)) {
    throw new Error(`Missing demo directory: ${examplesDir}`);
  }

  return walk(examplesDir)
    .filter((file) => file.endsWith(DEMO_EXTENSION))
    .map((file) => ({
      file,
      id: path
        .relative(examplesDir, file)
        .split(path.sep)
        .join('/')
        .slice(0, -DEMO_EXTENSION.length),
    }))
    .filter(({ id }) =>
      id.split('/').every((segment) => !segment.startsWith('_'))
    )
    .map(({ file, id }) => {
      if (id.includes('.')) {
        throw new Error(
          `Demo id cannot contain a dot: ${id}. Rename ${path.relative(examplesDir, file)}.`
        );
      }

      return { id, source: readCanonical(file) };
    })
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/**
 * Renders one demo's client boundary: the example re-exported from a module
 * carrying `'use client'`. The examples themselves stay framework-free, so the
 * source a reader copies is the component and nothing else.
 *
 * @param {DemoFile} demo
 * @returns {string}
 */
export function renderDemoBoundary(demo) {
  return `'use client';

${GENERATED_BY}
${REGENERATE_HINT}

export { default as Component } from ${JSON.stringify(exampleSpecifier(demo.id))};
`;
}

/**
 * Renders one demo's module: its component forwarded from the boundary, and
 * its source text as a plain string. This module carries no directive, so a
 * server component reading `source` gets the string rather than a client
 * reference.
 *
 * @param {DemoFile} demo
 * @returns {string}
 */
export function renderDemoModule(demo) {
  return `${GENERATED_BY}
${REGENERATE_HINT}

export { Component } from ${JSON.stringify(boundarySpecifier(demo.id))};

export const source = ${JSON.stringify(demo.source)};
`;
}

/**
 * Renders the index module for the given demos.
 *
 * @param {DemoFile[]} demos
 * @returns {string}
 */
export function renderDemoIndex(demos) {
  const entries = demos
    .map((demo) =>
      [
        `  ${JSON.stringify(demo.id)}: {`,
        `    id: ${JSON.stringify(demo.id)},`,
        `    load: () => import(${JSON.stringify(`./${MODULES_DIR}/${demo.id}`)}),`,
        `  },`,
      ].join('\n')
    )
    .join('\n');

  const literal = entries ? `{\n${entries}\n}` : '{}';

  return `${INDEX_HEADER}
export const demos = ${literal} satisfies Record<string, Demo>;

${INDEX_FOOTER}`;
}

/**
 * Regenerates the demo index and its per-demo modules on disk, and returns
 * what it wrote. A file is rewritten only when its content changed, and every
 * file under `outputDir` this run did not write is deleted.
 *
 * @param {{ examplesDir?: string, outputDir?: string }} [options]
 */
export function generateDemoIndex({
  examplesDir = EXAMPLES_DIR,
  outputDir = GENERATED_DIR,
} = {}) {
  const demos = collectDemos(examplesDir);
  const index = renderDemoIndex(demos);
  const modulesDir = path.join(outputDir, MODULES_DIR);
  const indexFile = path.join(outputDir, INDEX_FILE);

  writeIfChanged(indexFile, index);

  const keep = new Set([indexFile]);
  for (const demo of demos) {
    const moduleFile = path.join(modulesDir, `${demo.id}.ts`);
    const boundaryFile = path.join(
      path.dirname(moduleFile),
      `${boundarySpecifier(demo.id)}.ts`
    );

    writeIfChanged(moduleFile, renderDemoModule(demo));
    writeIfChanged(boundaryFile, renderDemoBoundary(demo));
    keep.add(moduleFile);
    keep.add(boundaryFile);
  }

  pruneOrphans(outputDir, keep);

  return { demos, index };
}

function generateAndLog() {
  const { demos } = generateDemoIndex();
  const plural = demos.length === 1 ? 'demo' : 'demos';
  console.log(
    `demo-index: ${demos.length} ${plural} -> ${path.relative(DOCS_ROOT, GENERATED_DIR)}`
  );
}

/** Regenerates without letting a broken examples/ state take the watcher down. */
function regenerateQuietly() {
  try {
    generateAndLog();
  } catch (error) {
    console.error(`demo-index: ${error.message}`);
  }
}

function watchExamples() {
  const relativeExamples = path.relative(DOCS_ROOT, EXAMPLES_DIR);

  regenerateQuietly();

  let watcher;
  try {
    watcher = watch(EXAMPLES_DIR, { recursive: true });
  } catch (error) {
    console.error(
      `demo-index: cannot watch ${relativeExamples} — ${error.message}`
    );
    process.exitCode = 1;
    return;
  }

  let pending;
  watcher.on('change', () => {
    clearTimeout(pending);
    pending = setTimeout(regenerateQuietly, WATCH_DEBOUNCE_MS);
  });
  watcher.on('error', (error) => {
    console.error('demo-index: watch failed —', error);
    process.exitCode = 1;
    watcher.close();
  });

  console.log(`demo-index: watching ${relativeExamples}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--watch')) {
    watchExamples();
  } else {
    generateAndLog();
  }
}
